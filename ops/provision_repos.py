#!/usr/bin/env python3
"""Provision one private GitHub repository per department.

Each repo gets a README describing the department, its manager, its charter and
its rules, plus a standard scaffold. Idempotent: re-running only updates the
README. Never writes secrets.

    python3 ops/provision_repos.py            # create/update all
    python3 ops/provision_repos.py --dry-run  # show what would happen
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "ops"))
sys.path.insert(0, str(ROOT / "ops" / "integrations"))
import astra  # noqa: E402
import github  # noqa: E402

# department -> (manager agent, repo slug, one-line purpose)
DEPARTMENTS = {
    "Engineering": ("astra-cto", "dept-engineering",
                    "Architecture, implementation, code review, release, infrastructure."),
    "Marketing": ("astra-cmo", "dept-marketing",
                  "Brand, positioning, content, distribution and demand generation."),
    "Business Development": ("astra-cbdo", "dept-business-development",
                             "Opportunity discovery, qualification, proposals, client relations."),
    "Product": ("astra-cpo", "dept-product",
                "Product and service definition, scoping, packaging and pricing."),
    "Operations": ("astra-coo", "dept-operations",
                   "Task tracking, scheduling, records, cost control and reporting."),
    "Quality": ("astra-cqo", "dept-quality",
                "Independent verification of all deliverables before they ship."),
    "Research": ("astra-cro", "dept-research",
                 "Market, technical and competitive intelligence for the company."),
}


def repo_readme(dept: str, manager: str, purpose: str, company_repo: str) -> str:
    return f"""# {dept} — AI ASTRA AGENCY

Department repository. Owned and operated by the **{dept}** department of
AI ASTRA AGENCY.

| | |
|---|---|
| Department | {dept} |
| Manager | `{manager}` |
| Company control plane | `{company_repo}` |
| Company | AI ASTRA AGENCY |

## Purpose
{purpose}

## How this department works
- The manager (`{manager}`) receives briefs from the CEO and decomposes them
  into specialist tasks.
- Specialists are created on demand with
  `python3 ops/astra.py hire <name> --dept {dept!r} --reports-to {manager}`.
- All work is verified before it leaves the department.
- Durable knowledge is written to `knowledge/`; nothing lives only in a chat.

## Layout
```
README.md          this file
CHARTER.md         the department's mandate and boundaries
knowledge/         durable, reusable department knowledge
work/              active and completed work records
```

## Rules
1. Never fabricate results, customers, revenue, reviews or capabilities.
2. Never commit secrets, keys, tokens or private keys. Ever.
3. Verify before delivery; record evidence.
4. Keep durable knowledge in `knowledge/`, not only in conversations.
5. Respect every platform's terms of service.

---
_This repository is part of AI ASTRA AGENCY, an autonomous digital agency
operated by AI agents. Content is generated by AI agents._
"""


def charter(dept: str, manager: str, purpose: str) -> str:
    return f"""# {dept} Department Charter

**Manager:** `{manager}`
**Reports to:** CEO (`astra-ceo`)

## Mandate
{purpose}

## Authority
The manager may create, brief, review, and retire specialists within this
department, and may commit to this repository. The manager may not:
- hold or use company secrets or wallets,
- make financial or legal commitments,
- change company-wide security policy,
- act outside this department's mandate without CEO approval.

## Deliverable standard
Every deliverable states its acceptance criteria up front and is verified
against them before delivery. Untested work is never reported as done.

## Escalation
Blockers, policy conflicts and anything high-risk go to the CEO, who escalates
to the Owner only when a human decision or credential is genuinely required.
"""


def run(cmd: list[str], cwd: Path) -> tuple[int, str]:
    p = subprocess.run(cmd, cwd=str(cwd), capture_output=True, text=True)
    return p.returncode, (p.stdout + p.stderr).strip()


def provision(owner: str, slug: str, files: dict[str, str], dry: bool) -> dict:
    full = f"{owner}/{slug}"
    exists = github.repo_exists(full)
    if dry:
        return {"repo": full, "existed": exists, "action": "update" if exists else "create"}
    if not exists:
        r = github.create_private_repo(slug, f"AI ASTRA AGENCY — department repository")
        if not r["ok"]:
            return {"repo": full, "error": r.get("error") or r}
        time.sleep(3)

    # clone, write files, push
    work = ROOT / ".tmp_repos" / slug
    if work.exists():
        subprocess.run(["rm", "-rf", str(work)])
    work.parent.mkdir(parents=True, exist_ok=True)
    token = github.token()
    url = f"https://x-access-token:{token}@github.com/{full}.git"
    rc, out = run(["git", "clone", "--depth", "1", url, str(work)], ROOT)
    if rc != 0:
        return {"repo": full, "error": f"clone failed: {out[:200]}"}

    for rel, content in files.items():
        p = work / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(content)
    for d in ("knowledge", "work"):
        (work / d).mkdir(exist_ok=True)
        keep = work / d / ".gitkeep"
        if not keep.exists():
            keep.write_text("")

    run(["git", "config", "user.email", "agents@astra-agency.dev"], work)
    run(["git", "config", "user.name", "AI ASTRA AGENCY"], work)
    run(["git", "add", "-A"], work)
    rc, out = run(["git", "commit", "-m",
                   f"docs: initialize {slug} charter and README"], work)
    if "nothing to commit" not in out:
        rc2, out2 = run(["git", "push", "origin", "HEAD"], work)
        if rc2 != 0:
            return {"repo": full, "error": f"push failed: {out2[:200]}"}
    subprocess.run(["rm", "-rf", str(work)])
    return {"repo": full, "action": "updated" if exists else "created", "ok": True}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()

    ident = github.whoami()
    if not ident.get("ok"):
        print("GitHub not reachable:", ident, file=sys.stderr)
        sys.exit(1)
    owner = ident["login"]
    company_repo = f"{owner}/astra-agency-coder"

    results = []
    for dept, (manager, slug, purpose) in DEPARTMENTS.items():
        files = {
            "README.md": repo_readme(dept, manager, purpose, company_repo),
            "CHARTER.md": charter(dept, manager, purpose),
        }
        r = provision(owner, slug, files, a.dry_run)
        results.append(r)
        print(json.dumps(r, ensure_ascii=False))

    out = ROOT / "company" / "departments" / "repos.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps({"owner": owner, "generated_at": astra.now(),
                               "repos": results}, indent=2))
    print(f"\nwrote {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
